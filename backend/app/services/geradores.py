_last_resultado: dict[tuple[str, str, str], str] = {}


@dataclass(frozen=True)
class ResultadoGerador:
    tipo: str
    resultado: str
    sistema_usado: str
    fallback: bool


def _normalize_lang(lang: str | None) -> str:
    if not lang:
        return "pt-BR"
    lowered = lang.strip().lower()
    if lowered.startswith("en"):
        return "en"
    return "pt-BR"


def _pool(tipo: str, sistema: str, lang: str) -> tuple[list[str], str, bool]:
    if tipo not in TABELAS:
        raise ValueError(f"tipo desconhecido: {tipo}")
    por_sistema = TABELAS[tipo]
    normalizado = sistema.strip().lower()
    key = normalizado if normalizado in por_sistema else FALLBACK_KEY
    idiomas = por_sistema[key]
    entries = idiomas.get(lang) or idiomas.get("pt-BR") or []
    if not entries:
        raise ValueError(f"tabela vazia: {tipo}/{key}/{lang}")
    return entries, key, key == FALLBACK_KEY


def sortear(
    *,
    tipo: str,
    sistema: str,
    lang: str | None = None,
    scope: str = "",
) -> ResultadoGerador:
    """Sorteia um item, evitando repetir o resultado imediatamente anterior no mesmo scope."""
    idioma = _normalize_lang(lang)
    entries, sistema_usado, is_fallback = _pool(tipo, sistema, idioma)
    cache_key = (scope, tipo, idioma)
    previous = _last_resultado.get(cache_key)
    candidates = [e for e in entries if e != previous] if previous and len(entries) > 1 else entries
    chosen = random.choice(candidates)
    _last_resultado[cache_key] = chosen
    return ResultadoGerador(
        tipo=tipo,
        resultado=chosen,
        sistema_usado=sistema_usado if not is_fallback else FALLBACK_KEY,
        fallback=is_fallback,
    )


def reset_cache() -> None:
    """Utilitário de teste."""
    _last_resultado.clear()
